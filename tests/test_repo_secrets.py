"""Repo handling, secret exclusion, code provenance, incremental embedding."""

import shutil
import subprocess

import pytest

import embedify
from embedify.config import EmbedderConfig, EmbedifyConfig, SinkConfig
from embedify.secrets import scan_text
from embedify.sinks import MemorySink


def _cfg() -> EmbedifyConfig:
    return EmbedifyConfig(
        embedders={"text": EmbedderConfig(backend="hash", model="hash", dim=32)},
        sink=SinkConfig(type="memory"))


def test_directory_walk_respects_gitignore_and_skips_junk(tmp_path):
    (tmp_path / ".gitignore").write_text("ignored.py\nignored_dir/\n")
    (tmp_path / "keep.py").write_text("def keep():\n    return 1\n")
    (tmp_path / "ignored.py").write_text("def ignored():\n    return 2\n")
    sub = tmp_path / "ignored_dir"
    sub.mkdir()
    (sub / "x.py").write_text("def x():\n    return 3\n")
    nm = tmp_path / "node_modules"
    nm.mkdir()
    (nm / "lib.js").write_text("function lib() { return 1; }")
    (tmp_path / "package-lock.json").write_text("{}")
    (tmp_path / "app.min.js").write_text("var a=1;")
    (tmp_path / "gen.py").write_text("# Code generated by tool. DO NOT EDIT.\ndef g():\n    pass\n")
    (tmp_path / "bin.py").write_bytes(b"\x00\x01\x02")
    result = embedify.embed(tmp_path, config=_cfg())
    uris = {r.source_uri for r in result.records}
    assert any(u.endswith("keep.py") for u in uris)
    assert not any("ignored" in u or "node_modules" in u or "lock" in u
                   or "min.js" in u or "gen.py" in u or "bin.py" in u for u in uris)


def test_secrets_excluded_and_reported_without_values(tmp_path):
    (tmp_path / ".env").write_text("API_KEY=supersecretvalue123\n")
    (tmp_path / "leaky.py").write_text('KEY = "AKIAIOSFODNN7EXAMPLE"\n')
    # Granularity is the whole FILE: one finding excludes even clean symbols.
    (tmp_path / "mixed.py").write_text(
        'def mixed_clean():\n    return 1\nTOKEN = "AKIAIOSFODNN7EXAMPLE"\n')
    (tmp_path / "clean.py").write_text("def clean():\n    return 42\n")
    result = embedify.embed(tmp_path, config=_cfg())
    uris = {r.source_uri for r in result.records}
    assert any(u.endswith("clean.py") for u in uris)
    assert not any(u.endswith(".env") or u.endswith("leaky.py") or u.endswith("mixed.py")
                   for u in uris)
    assert not any("mixed_clean" in r.text_preview for r in result.records)
    kinds = {f.kind for f in result.findings}
    assert "secret-file" in kinds and "aws-access-key" in kinds
    assert result.stats.secrets_found >= 2 and result.stats.files_skipped >= 2
    assert "AKIAIOSFODNN7EXAMPLE" not in repr(result.findings)
    assert "supersecretvalue123" not in repr(result.findings)


def test_scan_text_reports_kind_and_line_only():
    findings = scan_text('x = 1\npassword = "hunter2hunter2"\n', source_uri="f.py")
    assert [(f.kind, f.line) for f in findings] == [("generic-assignment", 2)]


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_code_records_carry_git_provenance(tmp_path):
    env = ["-c", "user.email=t@t.t", "-c", "user.name=t"]
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    (tmp_path / "mod.py").write_text("def add(a, b):\n    return a + b\n")
    subprocess.run(["git", "-C", str(tmp_path), "add", "."], check=True)
    subprocess.run(["git", "-C", str(tmp_path), *env, "commit", "-qm", "init"], check=True)
    sha = subprocess.run(["git", "-C", str(tmp_path), "rev-parse", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.strip()
    result = embedify.embed(tmp_path / "mod.py", config=_cfg())
    rec = next(r for r in result.records if r.metadata.get("symbol_name") == "add"
               or r.metadata.get("symbol") == "add")
    assert rec.metadata["commit"] == sha
    assert rec.metadata["branch"] in ("main", "master")
    assert rec.metadata["repo"] == tmp_path.name
    assert rec.metadata["path"] == "mod.py"
    assert rec.metadata["language"] == "python"
    assert rec.locator.line_start == 1


def test_incremental_skip_replace_delete(tmp_path):
    f = tmp_path / "a.txt"
    f.write_text("alpha bravo charlie")
    sink = MemorySink()
    first = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert first.stats.units_embedded >= 1

    second = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert second.stats.units_embedded == 0 and second.stats.files_skipped >= 1
    count = len(sink.records)

    f.write_text("delta echo foxtrot")
    third = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert third.stats.units_embedded >= 1 and third.stats.records_deleted >= 1
    assert len(sink.records) == count
    assert all("delta" in r.text_preview or "alpha" not in r.text_preview
               for r in sink.records)

    f.unlink()
    fourth = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert fourth.stats.records_deleted >= 1
    assert sink.records == []


def test_incremental_rename_is_delete_plus_new(tmp_path):
    old = tmp_path / "old.txt"
    old.write_text("renamed file content")
    sink = MemorySink()
    embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert any(r.source_uri.endswith("old.txt") for r in sink.records)
    old.rename(tmp_path / "new.txt")
    result = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    uris = {r.source_uri for r in sink.records}
    assert any(u.endswith("new.txt") for u in uris)
    assert not any(u.endswith("old.txt") for u in uris)
    assert result.stats.records_deleted >= 1  # old path's records removed
    assert result.stats.units_embedded >= 1   # renamed file embedded as new


def _git(cwd, *args):
    subprocess.run(["git", "-C", str(cwd), *args], check=True,
                   capture_output=True, text=True)


def _commit_all(cwd, message):
    _git(cwd, "add", ".")
    _git(cwd, "-c", "user.email=t@t.t", "-c", "user.name=t", "commit", "-qm", message)
    return subprocess.run(["git", "-C", str(cwd), "rev-parse", "HEAD"],
                          capture_output=True, text=True, check=True).stdout.strip()


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_incremental_unchanged_records_keep_original_commit_sha(tmp_path):
    # Documented behaviour: incremental runs skip unchanged files, so their
    # stored records keep the commit SHA from when they were embedded —
    # the SHA is provenance of the embedding run, not a live HEAD lookup.
    _git(tmp_path, "init", "-q")
    (tmp_path / "a.py").write_text("def a():\n    return 1\n")
    sha1 = _commit_all(tmp_path, "one")
    sink = MemorySink()
    embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    (tmp_path / "b.py").write_text("def b():\n    return 2\n")
    sha2 = _commit_all(tmp_path, "two")
    assert sha2 != sha1
    result = embedify.embed(tmp_path, config=_cfg(), sink=sink, incremental=True)
    assert result.stats.skipped_by_reason.get("unchanged", 0) >= 1
    a_records = [r for r in sink.records if r.source_uri.endswith("a.py")]
    assert a_records and all(r.metadata["commit"] == sha1 for r in a_records)
